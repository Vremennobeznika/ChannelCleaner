// The removal policy must not accept one observation or a name match.
const now=new Date('2026-11-23T10:00:00Z').getTime();
const fresh={userId:'1234567',status:'был давно',capturedAt:new Date(now).toISOString()};
const flagged={userId:'1234567',flaggedAt:new Date(now-P.GRACE_MS).toISOString(),removed:false};
assert.equal(P.canRemoveAfterGrace(flagged,fresh,now),true);
assert.equal(P.canRemoveAfterGrace({...flagged,flaggedAt:new Date(now-P.GRACE_MS+1).toISOString()},fresh,now),false);
assert.equal(P.canRemoveAfterGrace({...flagged,flaggedAt:''},fresh,now),false);
assert.equal(P.canRemoveAfterGrace({...flagged,userId:'9999999'},fresh,now),false);
assert.equal(P.canRemoveAfterGrace({...flagged,removed:true},fresh,now),false);
assert.equal(P.canRemoveAfterGrace(flagged,{...fresh,status:'был недавно'},now),false);
assert.equal(P.canRemoveAfterGrace(flagged,{...fresh,capturedAt:new Date(now-3600000).toISOString()},now),false);
assert.equal(P.canRemoveAfterGrace(flagged,{...fresh,capturedAt:new Date(now+3600000).toISOString()},now),false);
assert.equal(P.preserveReviewFlag(flagged,fresh).flaggedAt,flagged.flaggedAt);
