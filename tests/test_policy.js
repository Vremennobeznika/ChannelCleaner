const assert=require('node:assert/strict');
const P=require('../scanner.js');
assert.equal(P.isLongAgo('был(а) давно'),true);
assert.equal(P.isLongAgo('был давно'),true);
assert.equal(P.isLongAgo('БЫЛА ДАВНО'),true);
assert.equal(P.isLongAgo('last seen a long time ago'),true);
assert.equal(P.isLongAgo('был(а) недавно'),false);
assert.equal(P.isLongAgo('был(а) в течение месяца'),false);
assert.equal(P.isLongAgo('last seen within a month'),false);
assert.equal(P.isLongAgo(''),false);
assert.equal(P.isActivityStatus('был(а) недавно'),true);
assert.equal(P.isActivityStatus('был(а) 1 минуту назад'),true);
assert.equal(P.isActivityStatus('был(а) 33 минуты назад'),true);
assert.equal(P.isActivityStatus('был(а) в течение недели'),true);
assert.equal(P.isActivityStatus('был(а) давно'),true);
assert.equal(P.isActivityStatus('last seen within a month'),true);
assert.equal(P.isActivityStatus('неизвестно'),false);
assert.equal(P.isLongAgo('был(а) 33 минуты назад'),false);
assert.equal(P.isProtected('Кто-то\nАдминистратор\nбыл давно'),true);
assert.equal(P.isProtected('Someone creator'),true);
assert.equal(P.isProtected('Читатель'),false);
assert.equal(P.makeCandidate('Алексей','был давно','Алексей\nбыл давно').identityVerified,false);
assert.equal(P.makeCandidate('Маша','была недавно','Маша\nбыла недавно'),null);
assert.equal(P.makeCandidate('Владелец','был давно','Владелец\nбыл давно'),null);
assert.equal(P.makeCandidate('','был давно',''),null);
let csv=P.toCSV([{name:'=HYPERLINK("x")',status:'был давно',capturedAt:'2026-11-20T10:00:00Z'}]);
assert(csv.startsWith('\ufeff'));
assert(csv.includes('"\'=HYPERLINK(""x"")"'));
assert(csv.includes('Давно = больше месяца'));
assert(P.toCSV([{name:'Нина',status:'был давно',capturedAt:'2026-11-20'}], '=HYPERLINK("evil")').includes("'"+'=HYPERLINK'));
assert.equal(P.makeCandidate('Маша','был(а) давно','Маша\nАдминистратор'),null);
assert(csv.endsWith('\r\n'));
assert.equal(JSON.parse(require('node:fs').readFileSync(require('node:path').join(__dirname,'../manifest.json'),'utf8')).manifest_version,3);
console.log('Policy assertions OK');
